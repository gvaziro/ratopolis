/**
 * «Тем временем наверху» (EN-6): the human paper's line about a train pass, first match wins.
 * `scene` gives the lantern catches and the cheese share of the train.
 */
export function pickHumanHeadline(
  haul: Pick<HaulSummary, "rating" | "gained" | "crash">,
  scene: { stats: { lanternCaught: number }; items: { res: ResId; value: number; spark?: boolean; skip?: boolean }[] },
): string {
  if (haul.rating === "royal") return "Машинист: поезд будто стал легче";
  if ((haul.gained.trinkets ?? 0) > 0) return "Пассажир 1-го класса недосчитался часов";
  if (scene.stats.lanternCaught >= 3) return "Кондуктор клянётся, что видел крысу с фонарём";
  if (haul.crash) return "Задержка на линии: на путях мусор";
  let all = 0;
  let cheese = 0;
  for (const it of scene.items) {
    if (it.spark || it.skip) continue;
    const v = it.value * (RESOURCES[it.res].market ?? 0);
    all += v;
    if (it.res === "cheese") cheese += v;
  }
  if (all > 0 && cheese >= 0.3 * all) return "Вагон-ресторан остался без чеддера";
  return "Обычный рейс, без происшествий";
}

